RUNGS_CAP = tuple(bi.STRATA_RUNGS)   # the eleven; R_OLMO = R_CAP for every world
N_POS_FIRING = 200                   # well above the eligibility floor (20)

_BATTERY = None
_MANIFEST = None
_VERIFY = None
_X_A = None


def battery():
    global _BATTERY
    if _BATTERY is None:
        _BATTERY = bg.load_battery()
    return _BATTERY


def manifest():
    global _MANIFEST
    if _MANIFEST is None:
        _MANIFEST = bi.load_manifest(bi.CHECKPOINTS_PATH, sha_pin=bi.CHECKPOINTS_2I_SHA256)
    return _MANIFEST


def verify_fn():
    global _VERIFY
    if _VERIFY is None:
        _VERIFY = a2d.load_verify()
    return _VERIFY


def x_a_real():
    global _X_A
    if _X_A is None:
        _X_A = bi.sampler_counts_pythia("1b", RUNGS_CAP)
    return _X_A


def _w(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj))


def _latent(rng, x_a, x_b, mode):
    """A per-rung ranking latent built from x_A (real) and x_B
    (synthetic, but generated by this same world so fully controlled):
    'a_only' ranks by x_A (drives SHARED); 'b_only' ranks by x_B (drives
    LINEAGE); 'both' ranks by their standardized sum (drives BOTH);
    'independent' ignores both (drives NEITHER); 'inverted' ranks by
    minus their standardized sum (drives NEITHER, 'inverted' on both
    tests). Ties (heavy zero-inflation in x_A on most rungs) are broken
    by the same noise draw regardless of mode."""
    n = len(x_a)
    tie = rng.normal(size=n) * 0.01
    xa = np.asarray(x_a, dtype=np.float64)
    xb = np.asarray(x_b, dtype=np.float64)
    if mode == "a_only":
        return xa + tie
    if mode == "b_only":
        return xb + tie
    if mode == "both":
        return pw._rankz(xa) + pw._rankz(xb) + tie
    if mode == "independent":
        return rng.normal(size=n)
    if mode == "inverted":
        return -(pw._rankz(xa) + pw._rankz(xb)) + tie
    raise ValueError(mode)


def write_world(root, *, mode="a_only", degenerate_b=False, missing_endpoint=False,
                drifted_seal=False, halt=False, gate1_diff=False, seed=0) -> dict:
    root = Path(root)
    rng = np.random.default_rng(seed)
    bat = battery()
    man = manifest()
    verify = verify_fn()
    x_a = x_a_real()

    # ---------------------------------------------------------- x_B
    x_b = {}
    for r in RUNGS_CAP:
        cap = bat[r]
        if degenerate_b:
            counts = [32] * bt.N_ITEMS   # constant -> degenerate in every stratum
        else:
            counts = [int(rng.integers(0, bi.DRAWS_PER_ITEM + 1)) for _ in range(bt.N_ITEMS)]
        x_b[r] = counts
        rows = []
        for i, it in enumerate(cap["eval_items"]):
            k = counts[i]
            draws = [str(it["answer"])] * k + ["zzz"] * (bi.DRAWS_PER_ITEM - k)
            rows.append({"item": i, "draws": {"0": draws}})
        write_draws(bi.predictor_draws_path(root, r), rows)
        _w(bi.predictor_record_path(root, r), {"rung": r})

    psha = "WORLD-PREDICTOR-SEAL"
    _w(bi.predictor_seal_path(root), {"files": {}, "counts": {}, "sha256": psha,
                                      "tag": bi.PREDICTOR_SEAL_TAG, "sampling": {}})
    _w(bi.rung_set_path(root), {"R_OLMO": list(RUNGS_CAP), "R_CAP": list(RUNGS_CAP),
                                "R_EXTRA": [], "per_rung": {}, "endpoint_file_sha256": {}})
    _w(bi.power_path(root), {"A": {"declared_status": "POWERED", "declaration": "x"},
                             "B": {"declared_status": "POWERED", "declaration": "x"}})

    # ------------------------------------------------------- the sweep
    steps = bi.trained_steps_7b()
    n_steps = len(steps)
    first = {}
    for r in bt.RUNGS:
        if r in RUNGS_CAP:
            w = _latent(rng, x_a[r], x_b[r], mode)
            order = np.argsort(-w)
            first[r] = {int(i): steps[int(rank * n_steps / N_POS_FIRING)]
                       for rank, i in enumerate(order[:N_POS_FIRING])}
        else:
            first[r] = {}   # the other 23 rungs never fire — irrelevant to the tree

    entry_stage1 = bi.entry_7b(man, bi.ENDPOINT_STEP_7B)
    entry_main = bi.entry_main(man, bi.REPO_7B)
    commit_stage1 = entry_stage1["commit"]

    stage1_from_sweep = {}
    for step in steps:
        entry = bi.entry_7b(man, step)
        # every trained grid step — including the endpoint — is loaded
        # through the SAME candidate-file download path in the sweep
        # (unlike 2g/2h, whose final step === `main`, loaded a
        # different way with no download); only the from_config TWIN
        # (excluded from `steps`) needs no checkpoint record.
        _w(bi.checkpoint_record_path(root, step),
           {"sha256": dict(entry.get("lfs_sha256", {})),
            "loading_info": {"missing_keys": 0, "unexpected_keys": 0,
                             "mismatched_keys": 0}})
        for r in bt.RUNGS:
            cap = bat[r]
            bits = [int(i in first[r] and step >= first[r][i]) for i in range(bt.N_ITEMS)]
            conts = [f" {it['answer']}" if b else " zzz"
                    for b, it in zip(bits, cap["eval_items"])]
            rec = {"rung": r, "size": bi.SIZE_OUT, "family": bi.FAMILY, "step": step,
                  "commit": entry["commit"], "items_sha256": cap["items_sha256"],
                  "n": bt.N_ITEMS, "correct": sum(bits), "bits": bits, "continuations": conts,
                  "predictor_sha": psha, "seal_tag": bi.ENDPOINT_SEAL_TAG,
                  "answer_type": cap["answer_type"]}
            _w(bi.record_path(root, step, r), rec)
            if step == bi.ENDPOINT_STEP_7B:
                stage1_from_sweep[r] = rec

    # the from_config twin: all-zero, every rung (a referent, never a predictor)
    for r in bt.RUNGS:
        cap = bat[r]
        bits = [0] * bt.N_ITEMS
        conts = [" zzz"] * bt.N_ITEMS
        rec = {"rung": r, "size": bi.SIZE_OUT, "family": bi.FAMILY, "step": bi.TWIN,
              "commit": None, "kind": "from_config", "items_sha256": cap["items_sha256"],
              "n": bt.N_ITEMS, "correct": 0, "bits": bits, "continuations": conts,
              "predictor_sha": psha, "seal_tag": bi.ENDPOINT_SEAL_TAG,
              "answer_type": cap["answer_type"]}
        _w(bi.record_path(root, bi.TWIN, r), rec)

    # ----------------------------------------------------- the endpoint
    #
    # stage1_final carries the SAME bits/continuations as the sweep's
    # own step928646 record (so gate 1 passes on every world exactly as
    # it must on the real tree); `main` is a trivial all-zero
    # descriptive, never read by the tree.
    for r in bt.RUNGS:
        cap = bat[r]
        sw = stage1_from_sweep[r]
        ev = {"bits": sw["bits"], "correct": sw["correct"],
             "continuations": sw["continuations"]}
        ckpt = {"revision": entry_stage1["revision"], "commit": commit_stage1,
               "kind": entry_stage1["kind"], "files": list(entry_stage1.get("files", [])),
               "weight_sha256": "D", "config_source": "cs", "tokenizer_source": "ts"}
        rec = ep.item_record_2i(rung=r, family=bi.FAMILY, size=bi.SIZE_OUT,
                                which="stage1_final", cap=cap, ev=ev, ckpt=ckpt,
                                seal={"tag": bi.PREDICTOR_SEAL_TAG, "sha256": psha}, t_s=0.0)
        p = bi.endpoint_record_path(root, "stage1_final", r)
        _w(p, rec)

        bits0 = [0] * bt.N_ITEMS
        conts0 = [" zzz"] * bt.N_ITEMS
        ev0 = {"bits": bits0, "correct": 0, "continuations": conts0}
        ckpt_main = {"revision": entry_main["revision"], "commit": entry_main["commit"],
                    "kind": entry_main["kind"], "files": list(entry_main.get("files", [])),
                    "weight_sha256": "D", "config_source": "cs", "tokenizer_source": "ts"}
        rec_main = ep.item_record_2i(rung=r, family=bi.FAMILY, size=bi.SIZE_OUT, which="main",
                                     cap=cap, ev=ev0, ckpt=ckpt_main,
                                     seal={"tag": bi.PREDICTOR_SEAL_TAG, "sha256": psha}, t_s=0.0)
        _w(bi.endpoint_record_path(root, "main", r), rec_main)

    if missing_endpoint:
        bi.endpoint_record_path(root, "stage1_final", bt.RUNGS[0]).unlink()

    # --------------------------------------------------------- gate 1
    g = {"rungs": list(bt.RUNGS),
        "bit_diffs": {r: (1 if gate1_diff and r == bt.RUNGS[0] else 0) for r in bt.RUNGS},
        "continuation_diffs": {r: 0 for r in bt.RUNGS},
        "continuations_compared": {r: bt.N_ITEMS for r in bt.RUNGS},
        "digest_sweep": "D" * 64, "digest_endpoint": "D" * 64,
        "commit_sweep": commit_stage1, "commit_endpoint": commit_stage1,
        "prereg_tag": bi.PREREG_TAG}
    _w(bi.gate1_path(root), g)
    if halt:
        bi.halt_marker_path(root).write_text("synthetic halt\n")

    def blobs_bound(tag, paths, repo_root=None):
        return ["drifted"] if drifted_seal else []

    def blob_sha(tag, rel):
        p = bi.REPO / rel
        return bg.sha256_file(p) if p.is_file() else None

    return {"tag_exists": lambda t: t in (bi.PREREG_TAG, bi.PREDICTOR_SEAL_TAG,
                                          bi.ENDPOINT_SEAL_TAG),
            "blob_sha": blob_sha, "blobs_bound": blobs_bound}


def run_world(root, seal, *, n_perm=300, n_boot=30) -> dict:
    return an.run(root=root, n_perm=n_perm, n_boot=n_boot, referents_sha=None,
                  manifest_sha=bi.CHECKPOINTS_2I_SHA256, **seal)


def world_specs() -> list:
    return [
        ("W1 SHARED", dict(mode="a_only"), "SHARED"),
        ("W2 LINEAGE", dict(mode="b_only"), "LINEAGE"),
        ("W3 BOTH", dict(mode="both"), "BOTH"),
        ("W4 NEITHER independent", dict(mode="independent"), "NEITHER"),
        ("W5 NEITHER inverted", dict(mode="inverted"), "NEITHER"),
        ("W6 INSUFFICIENT missing endpoint",
         dict(mode="a_only", missing_endpoint=True), "INSUFFICIENT_DATA"),
        ("W7 INSUFFICIENT drifted seal",
         dict(mode="a_only", drifted_seal=True), "INSUFFICIENT_DATA"),
        ("W8 INSUFFICIENT halted", dict(mode="a_only", halt=True), "INSUFFICIENT_DATA"),
        ("W9 INSUFFICIENT gate-1 diff",
         dict(mode="a_only", gate1_diff=True), "INSUFFICIENT_DATA"),
        ("W10 INSUFFICIENT degenerate x_B",
         dict(mode="a_only", degenerate_b=True), "INSUFFICIENT_DATA"),
    ]
