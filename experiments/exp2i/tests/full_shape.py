# experiments/exp2i/tests/full_shape.py
"""Synthetic full-shape 2i trees. x_A is NEVER synthesized: every world
uses `battery_2i.sampler_counts_pythia("1b", STRATA_RUNGS)` — the real,
committed 2d draws — as Test A's predictor, exactly as the real run
will. x_B (2i's own sealed draws, which do not exist yet) is written in
2d's row format for the eleven strata rungs and re-derived through
`battery_2i.sampler_counts_olmo`, exactly the production reader. The
7B sweep — a tree nobody has queried yet — is synthetic, built so each
of the eleven rungs' outcome ranking is a controlled function of x_A
and/or x_B: A-only (SHARED), B-only (LINEAGE), both (BOTH), independent
(NEITHER), anti-correlated with both (NEITHER, 'inverted' on both). The
other 23 rungs and the from_config twin are all-zero — their exact
values never enter the primary tree (design §3.6: no twin/SURFACE
terminal). Every record sits in the production layout, read by
`analyze_2i.run` through the same loaders the real run uses; R_OLMO =
R_CAP = the eleven for every world (R_EXTRA empty) — no extra-rung
degrees of freedom are needed to reach every terminal."""

