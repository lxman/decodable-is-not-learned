"""The mutants `mutation_check_6.py` runs. Each is one textual change to
one file of Exp 6 that a correct instrument must notice: a gate that
stops refusing, a bar moved by one, a re-derivation that stops
comparing, an order reversed. `old` must occur EXACTLY ONCE in `file`.

`suite`: which fast files judge it ("battery" or "instrument").
`hint`: the slow test most likely to kill a mutant the fast files
cannot see, as `file::expression` (tried before the whole slow suite).
"""


def _m(file, name, old, new, suite="instrument", hint=None):
    m = {"file": file, "name": name, "old": old, "new": new, "suite": suite}
    if hint:
        m["hint"] = hint
    return m


def _b(file, name, old, new):
    return _m(file, name, old, new, suite="battery")


